#!/usr/bin/env python3
"""D4 bounded r3 audit: exact delta + Pointer cases; does not re-run the r2 suite."""
import argparse
import copy
import difflib
import hashlib
import json
import sys
from importlib.metadata import version
from pathlib import Path
from jsonschema import Draft202012Validator

ROOT = Path('/Users/mac/AinerWorkFlow/AinerHub_IDEA')
OUT = ROOT / 'reports/production-brain/D1-independent-r3'
PRIOR = ROOT / 'reports/production-brain/D1-independent-r2'
ARCHIVE = ROOT / 'reports/production-brain/D1-r3'
SCHEMA = ROOT / 'docs/v2/production_brain/performance_interface_v0.schema.json'
DOC = ROOT / 'docs/v2/production_brain/performance_interface_v0.md'


def identity(p):
    data = p.read_bytes()
    return {'path': str(p), 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}


def pointer_valid(value):
    """Token scanner independent of the schema regex; RFC6901 string form."""
    if not isinstance(value, str):
        return False
    if value == '':
        return True
    if not value.startswith('/'):
        return False
    for token in value.split('/')[1:]:
        i = 0
        while i < len(token):
            if token[i] == '~':
                if i + 1 == len(token) or token[i + 1] not in '01':
                    return False
                i += 2
            else:
                i += 1
    return True


def diff_json(a, b, path=''):
    if type(a) is not type(b):
        return [{'path': path, 'before': a, 'after': b}]
    if isinstance(a, dict):
        rows = []
        for key in sorted(set(a) | set(b)):
            p = path + '/' + str(key)
            if key not in a or key not in b:
                rows.append({'path': p, 'before': a.get(key), 'after': b.get(key)})
            else:
                rows.extend(diff_json(a[key], b[key], p))
        return rows
    if isinstance(a, list):
        if len(a) != len(b):
            return [{'path': path, 'before': a, 'after': b}]
        return [r for i, (x, y) in enumerate(zip(a, b)) for r in diff_json(x, y, path + '/' + str(i))]
    return [] if a == b else [{'path': path, 'before': a, 'after': b}]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--failure-control', action='store_true')
    args = parser.parse_args()
    schema = json.loads(SCHEMA.read_text())
    old_schema_path = ARCHIVE / 'r2-performance_interface_v0.schema.json'
    old_doc_path = ARCHIVE / 'r2-performance_interface_v0.md'
    old_schema = json.loads(old_schema_path.read_text())
    Draft202012Validator.check_schema(schema)
    validator = Draft202012Validator(schema)
    differences = diff_json(old_schema, schema)
    allowed = '/oneOf/2/properties/errors/items/properties/path/pattern'
    expected_pattern = r'^(?:/(?:[^~/]|~[01])*)*$'
    old_ids = json.loads((PRIOR / 'results.json').read_text())['identities']
    prior_hash = {Path(row['path']).name: row['sha256'] for row in old_ids}
    declared = json.loads((ARCHIVE / 'identities.json').read_text())
    current_ids = {str(p): identity(p) for p in [SCHEMA, DOC]}
    prior_manifest = json.loads((PRIOR / 'artifact-identities.json').read_text())
    old_evidence_before = {str(p): identity(p) for p in PRIOR.iterdir() if p.is_file()}
    checks = {
        'r3_hashes_match_author': all(current_ids[row['path']]['sha256'] == row['sha256'] for row in declared),
        'r2_schema_archive_matches_reviewed_input': identity(old_schema_path)['sha256'] == prior_hash['performance_interface_v0.schema.json'],
        'r2_doc_archive_matches_reviewed_input': identity(old_doc_path)['sha256'] == prior_hash['performance_interface_v0.md'],
        'schema_exact_one_changed_leaf': len(differences) == 1 and differences[0]['path'] == allowed,
        'schema_only_expected_pattern_changed': len(differences) == 1 and differences[0]['before'] == r'^(/|$)' and differences[0]['after'] == expected_pattern,
        'schema_bytes_identical_after_reverting_pattern': SCHEMA.read_text().replace(expected_pattern, r'^(/|$)', 1) == old_schema_path.read_text(),
        'r2_all_manifest_files_unchanged': all(identity(Path(row['path']))['sha256'] == row['sha256'] for row in prior_manifest),
    }
    old_doc = old_doc_path.read_text()
    new_doc = DOC.read_text()
    addition = '\nr3 仅收紧 errors[].path：空串表示根，非根由 / 分隔；每个 token 中 ~ 只允许 ~0 或 ~1。r2 原字节保存在 reports/production-brain/D1-r3/r2-*，独立复核原失败不覆盖。其余 r2 合同不变。\n'
    checks['doc_only_revision_marker_and_pointer_addition'] = new_doc == old_doc.replace('草案 r2，', '草案 r3，', 1) + addition
    # Original six fixtures are read unchanged, not regenerated by the old script.
    original = json.loads((PRIOR / 'pointer-contract-results.json').read_text())['cases']
    rows = []
    for case in original:
        instance = copy.deepcopy(case['instance'])
        actual = validator.is_valid(instance)
        rows.append({'source': 'r2-original-six', 'pointer': case['pointer'],
                     'expected_valid': case['expected_valid'], 'r2_actual_valid': case['actual_valid'],
                     'actual_valid': actual, 'pass': actual == case['expected_valid']})
    values = ['/', '//', '/a/', '/~0', '/~1', '/~01', '/~10', '/~00/~11',
              '/角色/眼睛', '/emoji/👁', '/back\\slash', '/line\nbreak', '/nul\u0000token',
              '/~2', '/a~x/b', '/~~0', '/~0~', '/~1~2', '/a/b~', '/~9',
              '#/a', 'a/b', ' ', '~0', None, 0]
    for i, value in enumerate(values):
        instance = copy.deepcopy(original[0]['instance'])
        instance['errors'][0]['path'] = value
        expected = pointer_valid(value)
        actual = validator.is_valid(instance)
        rows.append({'source': 'independent-token-scanner-boundary', 'pointer': value,
                     'expected_valid': expected, 'actual_valid': actual, 'pass': actual == expected})
    # Same field must not weaken adjacent error shape/enumeration rules.
    neighbor = []
    base = copy.deepcopy(original[1]['instance'])
    for name, mutate in [
        ('unknown_error', lambda d: d['errors'][0].update(code='unknown_code')),
        ('missing_path', lambda d: d['errors'][0].pop('path')),
        ('missing_message', lambda d: d['errors'][0].pop('message')),
        ('empty_errors', lambda d: d.update(errors=[])),
        ('success_curves_in_error', lambda d: d.update(curves=[])),
    ]:
        data = copy.deepcopy(base)
        mutate(data)
        valid = validator.is_valid(data)
        neighbor.append({'case': name, 'expected_valid': False, 'actual_valid': valid, 'pass': not valid})
    if args.failure_control:
        rows.append({'source': 'intentional-expectation-failure', 'pointer': '',
                     'expected_valid': False, 'actual_valid': validator.is_valid(original[0]['instance']), 'pass': False})
    checks['old_evidence_directory_unchanged_during_audit'] = old_evidence_before == {
        str(p): identity(p) for p in PRIOR.iterdir() if p.is_file()}
    checks['no_model_imports'] = not any(name.split('.')[0] in {'mlx', 'torch', 'tensorflow'} for name in sys.modules)
    ids = [identity(p) for p in [SCHEMA, DOC, old_schema_path, old_doc_path, ARCHIVE / 'identities.json',
                                   PRIOR / 'results.json', PRIOR / 'pointer-contract-results.json',
                                   PRIOR / 'artifact-identities.json']]
    failed = sum(not row['pass'] for row in rows + neighbor) + sum(not value for value in checks.values())
    result = {'scope': 'D1 r3 bounded delta/Pointer audit; prior 94 tests reused, not rerun',
              'python': sys.version, 'jsonschema': version('jsonschema'), 'schema_meta_valid': True,
              'pointer_passed': sum(row['pass'] for row in rows), 'pointer_total': len(rows),
              'neighbor_passed': sum(row['pass'] for row in neighbor), 'neighbor_total': len(neighbor),
              'failed': failed, 'checks': checks, 'schema_diff': differences,
              'pointer_cases': rows, 'neighbor_cases': neighbor, 'inputs': ids}
    suffix = '-failure-control' if args.failure_control else ''
    (OUT / ('results' + suffix + '.json')).write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
    (OUT / ('schema-diff' + suffix + '.json')).write_text(json.dumps(differences, indent=2) + '\n')
    if not args.failure_control:
        (OUT / 'document-diff.patch').write_text(''.join(difflib.unified_diff(old_doc.splitlines(True), new_doc.splitlines(True), fromfile=str(old_doc_path), tofile=str(DOC))))
        (OUT / 'r2-evidence-unchanged.json').write_text(json.dumps(list(old_evidence_before.values()), indent=2) + '\n')
    print(json.dumps({key: result[key] for key in ['scope', 'pointer_passed', 'pointer_total', 'neighbor_passed', 'neighbor_total', 'checks', 'failed']}, ensure_ascii=False, indent=2))
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main())
